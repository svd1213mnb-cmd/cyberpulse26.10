/* ==========================================================================
       5. СОСТОЯНИЕ (STATE) И LOCALSTORAGE
       ========================================================================== */
window.LS_KEY = "cyberPulsestate";
window.LS_SETTINGS = "cyberPulseSettings";
window.loadState = function () {
  try {
    const raw = localStorage.getItem(window.LS_KEY);
    return raw ? JSON.parse(raw) : null;
  } catch {
    return null;
  }
};

window.loadSettings = function () {
  try {
    return JSON.parse(localStorage.getItem(window.LS_SETTINGS) || "{}");
  } catch {
    return {};
  }
};
// Функция сохранения настроек
window.saveSettings = function (s) {
  localStorage.setItem("cyberPulseSettings", JSON.stringify(s));
};
